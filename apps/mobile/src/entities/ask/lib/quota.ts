/**
 * 이번 달 사용량을 화면에 보이는 퍼센트로. 서버는 실제 모델 비용으로 세고 비율만 준다.
 *
 * 횟수로는 말하지 않는다. 한 쪽에서 다섯 문장을 묻는 것과 한 문장을 묻는 것은 비용이 몇 배
 * 다르다 — "N번 남았어요"는 다음 질문이 얼마나 쓸지 모르는 채로 하는 약속이라, 남았다던
 * 횟수보다 먼저 바닥나면 독자는 속았다고 느낀다. 퍼센트는 쓴 만큼만 말한다.
 *
 * 조금이라도 썼으면 1% 이상으로 보인다. 0.3%를 0%로 반올림하면 물었는데 아무것도 안
 * 줄어든 것처럼 보인다. 마지막 질문이 예산을 넘겨도 100%에서 멈춘다.
 */
export function usagePercent(ratio: number | undefined): number {
  if (!ratio || ratio <= 0) return 0;
  return Math.min(100, Math.max(1, Math.round(ratio * 100)));
}
